/** 나라의 도시 선택지: 대표 도시 + 이미 등록된 도시(중복 제거, 가나다순으로 뒤에 덧붙임) */
export function cityOptions(country, registered = []) {
  const base = CITY_PRESETS[String(country || '').toUpperCase()] || [];
  const seen = new Set(base);
  const extra = registered
    .filter((c) => c && !seen.has(c))
    .sort((a, b) => a.localeCompare(b, 'ko'));
  return [...base, ...new Set(extra)];
}
